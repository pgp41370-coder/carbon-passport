def banner(c) -> None:
    c.rect(30, 18, PAGE_W - 60, 18, fill=0.88)
    c.text(38, 30.5, BANNER, 7.4, "bold")
    c.line(30, PAGE_H - 34, PAGE_W - 30, PAGE_H - 34)
    c.text(30, PAGE_H - 22, FOOTER, 7)
    c.text(PAGE_W - 108, PAGE_H - 22, "SYNTHETIC SAMPLE", 7, "bold")


def table(c, x: float, y: float, widths: list[float], rows: list[list[str]], row_h: float = 18, size: float = 8.5) -> float:
    """Draws a bordered table with a shaded header row; returns the y below it."""
    total_w = sum(widths)
    for r, row in enumerate(rows):
        top = y + r * row_h
        c.rect(x, top, total_w, row_h, fill=0.93 if r == 0 else None)
        cx = x
        for w, cell in zip(widths, row):
            c.text(cx + 4, top + row_h - 5.5, cell, size, "bold" if r == 0 else "regular")
            cx += w
        cx = x
        for w in widths[:-1]:
            cx += w
            c.line(cx, top, cx, top + row_h)
    return y + len(rows) * row_h


def fields(c, x: float, y: float, pairs: list[tuple[str, str]], label_w: float = 120, size: float = 9, gap: float = 14) -> float:
    for i, (label, value) in enumerate(pairs):
        c.text(x, y + i * gap, label, size, "bold")
        c.text(x + label_w, y + i * gap, value, size)
    return y + len(pairs) * gap


def signature(c, x: float, y: float, for_line: str, role: str) -> None:
    c.text(x, y, for_line, 8.5, "bold")
    c.line(x, y + 34, x + 190, y + 34)
    c.text(x, y + 46, role, 8)


