class PdfCanvas:
    """Minimal single-page PDF writer using the standard Helvetica/Courier fonts."""

    FONTS = {"regular": "F1", "bold": "F2", "mono": "F3"}

    def __init__(self, title: str) -> None:
        self.title = title
        self.ops: list[str] = []

    @staticmethod
    def _escape(text: str) -> str:
        text.encode("ascii")  # standard fonts + WinAnsi: keep content ASCII
        return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    def text(self, x: float, y: float, s: str, size: float = 9, style: str = "regular") -> None:
        font = self.FONTS[style]
        self.ops.append(f"BT /{font} {size} Tf {x:.2f} {PAGE_H - y:.2f} Td ({self._escape(s)}) Tj ET")

    def line(self, x1: float, y1: float, x2: float, y2: float, width: float = 0.6) -> None:
        self.ops.append(f"{width} w {x1:.2f} {PAGE_H - y1:.2f} m {x2:.2f} {PAGE_H - y2:.2f} l S")

    def rect(self, x: float, y: float, w: float, h: float, fill: float | None = None, width: float = 0.6) -> None:
        box = f"{x:.2f} {PAGE_H - y - h:.2f} {w:.2f} {h:.2f} re"
        if fill is not None:
            self.ops.append(f"{fill} g {box} f 0 g")
        self.ops.append(f"{width} w {box} S")

    def save(self, path: Path) -> None:
        content = "\n".join(self.ops).encode("latin-1")
        objects = [
            b"<< /Type /Catalog /Pages 2 0 R >>",
            b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            (
                f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PAGE_W} {PAGE_H}] /Contents 4 0 R "
                "/Resources << /Font << /F1 5 0 R /F2 6 0 R /F3 7 0 R >> >> >>"
            ).encode(),
            b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>",
            (
                f"<< /Title ({self._escape(self.title)}) /Subject (Synthetic sample document - not a real record) "
                "/Producer (Carbon Passport sample-pack generator) >>"
            ).encode(),
        ]
        out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
        offsets = []
        for number, body in enumerate(objects, start=1):
            offsets.append(len(out))
            out += f"{number} 0 obj\n".encode() + body + b"\nendobj\n"
        xref_at = len(out)
        out += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
        for offset in offsets:
            out += f"{offset:010d} 00000 n \n".encode()
        out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R /Info 8 0 R >>\nstartxref\n{xref_at}\n%%EOF\n".encode()
        path.write_bytes(bytes(out))


class ImageCanvas:
    """Renders the same drawing calls to a 150 dpi raster page."""

    DPI = 150

    def __init__(self) -> None:
        self.scale = self.DPI / 72
        self.image = Image.new("L", (round(PAGE_W * self.scale), round(PAGE_H * self.scale)), 255)
        self.draw = ImageDraw.Draw(self.image)
        self._fonts: dict[tuple[str, float], ImageFont.FreeTypeFont] = {}

    def _font(self, style: str, size: float) -> ImageFont.FreeTypeFont:
        key = (style, size)
        if key not in self._fonts:
            name = {"regular": "Arial.ttf", "bold": "Arial Bold.ttf", "mono": "Courier New.ttf"}[style]
            self._fonts[key] = ImageFont.truetype(str(FONT_DIR / name), round(size * self.scale))
        return self._fonts[key]

    def _p(self, value: float) -> float:
        return value * self.scale

    def text(self, x: float, y: float, s: str, size: float = 9, style: str = "regular") -> None:
        self.draw.text((self._p(x), self._p(y)), s, fill=20, font=self._font(style, size), anchor="ls")

    def line(self, x1: float, y1: float, x2: float, y2: float, width: float = 0.6) -> None:
        self.draw.line(
            [(self._p(x1), self._p(y1)), (self._p(x2), self._p(y2))], fill=40, width=max(1, round(width * self.scale))
        )

    def rect(self, x: float, y: float, w: float, h: float, fill: float | None = None, width: float = 0.6) -> None:
        box = [self._p(x), self._p(y), self._p(x + w), self._p(y + h)]
        self.draw.rectangle(
            box,
            fill=None if fill is None else round(fill * 255),
            outline=40,
            width=max(1, round(width * self.scale)),
        )

    def scanned(self, angle: float, noise: bool) -> Image.Image:
        """Gives the page a mild scanned look: slight skew, paper tone, optional noise."""
        page = self.image.rotate(angle, resample=Image.BICUBIC, expand=False, fillcolor=255)
        if noise:
            grain = Image.effect_noise(page.size, 18).point(lambda v: 255 - (255 - v) // 6)
            page = Image.composite(page, grain, page.point(lambda v: 255 if v < 200 else 0))
            page = page.filter(ImageFilter.GaussianBlur(0.5))
        return page


